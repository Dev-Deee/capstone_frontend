package semicolonEstore;

public class Users {
    private String name;
    private String email;
    private String password;
    private String phoneNumber;
    private String address;
    private int age;


    public Users(String name, String email, String password, String phoneNumber, String address, int age){
        this.name = name;
        this.email = email;
        this.password = password;
        this.phoneNumber = phoneNumber;
        this.address = address;
        this.age = age;
    }
}
